const Product = require("../models/product");

// Get Product Recommendations
const getRecommendations = async (req, res) => {
    try {
        const { category, maxPrice } = req.query;

        // Get products from MongoDB
        const products = await Product.find();

        if (products.length === 0) {
            return res.status(404).json({
                message: "No products available"
            });
        }

        // If RapidMiner is configured, send data to it
        if (process.env.RAPIDMINER_API_URL) {
            const response = await fetch(
                process.env.RAPIDMINER_API_URL,
                {
                    method: "POST",
                    headers: {
                        "Content-Type": "application/json",
                        ...(process.env.RAPIDMINER_API_TOKEN && {
                            Authorization:
                                `Bearer ${process.env.RAPIDMINER_API_TOKEN}`
                        })
                    },
                    body: JSON.stringify({
                        products: products.map(product => ({
                            id: product._id,
                            name: product.name,
                            category: product.category,
                            price: product.price
                        })),
                        preferences: {
                            category: category || null,
                            maxPrice: maxPrice
                                ? Number(maxPrice)
                                : null
                        }
                    })
                }
            );

            if (!response.ok) {
                return res.status(502).json({
                    message: "RapidMiner recommendation request failed"
                });
            }

            const recommendations = await response.json();

            return res.status(200).json({
                message: "Recommendations generated by RapidMiner",
                data: recommendations
            });
        }

        // Basic recommendation mode (without RapidMiner)
        let recommendations = products;

        if (category) {
            recommendations = recommendations.filter(
                product =>
                    product.category.toLowerCase() ===
                    category.toLowerCase()
            );
        }

        if (maxPrice !== undefined) {
            const budget = Number(maxPrice);

            if (!Number.isFinite(budget) || budget < 0) {
                return res.status(400).json({
                    message: "Invalid maxPrice value"
                });
            }

            recommendations = recommendations.filter(
                product => product.price <= budget
            );
        }

        return res.status(200).json({
            message: "Basic product recommendations",
            data: recommendations
        });

    } catch (error) {
        return res.status(500).json({
            message: error.message
        });
    }
};

module.exports = {
    getRecommendations
};

